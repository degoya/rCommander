use super::*;
use crate::test_support::{self, names as listed};

const SHA256_ABC: &str = "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad";
const SHA256_EMPTY: &str = "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855";

fn names(list: &[&str]) -> Vec<String> {
    list.iter().map(|name| (*name).to_owned()).collect()
}

#[tokio::test]
async fn one_combined_file_holds_every_file_of_the_selection() {
    let (root, vfs) = test_support::local();
    test_support::write(root.path(), "a.txt", b"abc");
    test_support::write(root.path(), "sub/z.txt", b"");
    test_support::write(root.path(), "sub/deeper/b.txt", b"abc");
    let control = Control::new();
    let report = create(
        &vfs,
        root.path(),
        &names(&["a.txt", "sub"]),
        Algorithm::Sha256,
        &Layout::Combined { file_name: None },
        &control,
    )
    .await
    .expect("created");
    // The progress of a job: three files of six bytes, all of them hashed.
    assert_eq!(
        (
            control.files_done(),
            control.files_total(),
            control.bytes_total()
        ),
        (3, 3, 6)
    );
    assert_eq!(report.written, vec!["checksums.sha256"]);
    let text = std::fs::read_to_string(root.path().join("checksums.sha256")).expect("written");
    assert_eq!(
        text,
        format!("{SHA256_ABC} *a.txt\n{SHA256_EMPTY} *sub/z.txt\n{SHA256_ABC} *sub/deeper/b.txt\n")
    );
}

#[tokio::test]
async fn a_single_file_names_the_combined_file_and_a_name_can_be_given() {
    let (root, vfs) = test_support::local();
    test_support::write(root.path(), "disk.iso", b"abc");
    let control = Control::new();
    let single = create(
        &vfs,
        root.path(),
        &names(&["disk.iso"]),
        Algorithm::Md5,
        &Layout::Combined { file_name: None },
        &control,
    )
    .await
    .expect("created");
    assert_eq!(single.written, vec!["disk.iso.md5"]);
    assert_eq!(control.bytes_done(), 3);
    let named = create(
        &vfs,
        root.path(),
        &names(&["disk.iso"]),
        Algorithm::Crc32,
        &Layout::Combined {
            file_name: Some("all.sfv".to_owned()),
        },
        &Control::new(),
    )
    .await
    .expect("created");
    assert_eq!(named.written, vec!["all.sfv"]);
    let sfv = std::fs::read_to_string(root.path().join("all.sfv")).expect("written");
    assert_eq!(sfv, "; Generated by rCommander\ndisk.iso 352441C2\n");
}

#[tokio::test]
async fn one_file_per_file_lies_beside_it_and_names_only_it() {
    let (root, vfs) = test_support::local();
    test_support::write(root.path(), "a.txt", b"abc");
    test_support::write(root.path(), "sub/b.txt", b"");
    let report = create(
        &vfs,
        root.path(),
        &names(&["a.txt", "sub"]),
        Algorithm::Sha256,
        &Layout::PerFile,
        &Control::new(),
    )
    .await
    .expect("created");
    assert_eq!(report.written, vec!["a.txt.sha256", "sub/b.txt.sha256"]);
    assert_eq!(
        std::fs::read_to_string(root.path().join("a.txt.sha256")).expect("a"),
        format!("{SHA256_ABC} *a.txt\n")
    );
    assert_eq!(
        std::fs::read_to_string(root.path().join("sub").join("b.txt.sha256")).expect("b"),
        format!("{SHA256_EMPTY} *b.txt\n")
    );
}

#[tokio::test]
async fn an_existing_checksum_file_stops_the_run_before_anything_is_written() {
    let (root, vfs) = test_support::local();
    test_support::write(root.path(), "a.txt", b"abc");
    test_support::write(root.path(), "b.txt", b"abc");
    test_support::write(root.path(), "b.txt.sha256", b"mine");
    let error = create(
        &vfs,
        root.path(),
        &names(&["a.txt", "b.txt"]),
        Algorithm::Sha256,
        &Layout::PerFile,
        &Control::new(),
    )
    .await
    .expect_err("exists");
    assert_eq!(error.code(), "already_exists");
    assert_eq!(listed(root.path()), vec!["a.txt", "b.txt", "b.txt.sha256"]);
    assert_eq!(
        std::fs::read(root.path().join("b.txt.sha256")).expect("kept"),
        b"mine"
    );
}

#[tokio::test]
async fn bad_names_empty_selections_and_a_cancel_write_nothing() {
    let (root, vfs) = test_support::local();
    test_support::write(root.path(), "a.txt", b"abc");
    std::fs::create_dir(root.path().join("empty")).expect("dir");
    let run = |list: &'static [&'static str], control: Control| {
        let vfs = Arc::clone(&vfs);
        let dir = root.path().to_path_buf();
        async move {
            create(
                &vfs,
                &dir,
                &names(list),
                Algorithm::Sha1,
                &Layout::Combined { file_name: None },
                &control,
            )
            .await
            .expect_err("refused")
            .code()
        }
    };
    assert_eq!(run(&["../a.txt"], Control::new()).await, "invalid_name");
    assert_eq!(run(&["empty"], Control::new()).await, "checksum_no_files");
    assert_eq!(run(&["missing"], Control::new()).await, "not_found");
    let cancelled = Control::new();
    cancelled.cancel();
    assert_eq!(run(&["a.txt"], cancelled).await, "cancelled");
    assert_eq!(listed(root.path()), vec!["a.txt", "empty"]);
}

/// A folder holding a file the run's guard refuses fails with `sensitive_path` and writes
/// nothing: no checksum file carries its digest.
#[tokio::test]
async fn a_guarded_file_inside_a_folder_stops_the_run_before_anything_is_written() {
    let (root, vfs) = test_support::local();
    test_support::write(root.path(), "keys/a.txt", b"abc");
    test_support::write(root.path(), "keys/deeper/id_rsa", b"secret");
    let control = Control::new().with_guard(std::sync::Arc::new(|path: &std::path::Path| {
        (path.file_name()? == "id_rsa").then_some("a test key")
    }));
    let error = create(
        &vfs,
        root.path(),
        &names(&["keys"]),
        Algorithm::Sha256,
        &Layout::Combined { file_name: None },
        &control,
    )
    .await
    .expect_err("refused");
    assert_eq!(error.code(), "sensitive_path");
    assert_eq!(listed(root.path()), vec!["keys"]);
}

/// No name given (an MCP call, an emptied field) for a folder holding one file: the combined
/// file lies in the folder, as for any folder, and checks out against its own line - not
/// `docs/a.txt.sha256` naming `docs/a.txt` from inside `docs`.
#[tokio::test]
async fn a_folder_with_one_file_gets_the_combined_file_beside_the_folder() {
    let (root, vfs) = test_support::local();
    test_support::write(root.path(), "docs/a.txt", b"abc");
    let report = create(
        &vfs,
        root.path(),
        &names(&["docs"]),
        Algorithm::Sha256,
        &Layout::Combined { file_name: None },
        &Control::new(),
    )
    .await
    .expect("created");
    assert_eq!(report.written, vec!["checksums.sha256"]);
    let text = std::fs::read_to_string(root.path().join("checksums.sha256")).expect("written");
    assert_eq!(text, format!("{SHA256_ABC} *docs/a.txt\n"));
    let checked = crate::verify(&vfs, &root.path().join("checksums.sha256"), &Control::new())
        .await
        .expect("checked");
    assert_eq!(checked.summary.ok, 1);
    assert_eq!(listed(&root.path().join("docs")), vec!["a.txt"]);
}

/// The progress window's File bar (RC-010-07): caught half way through the second file, the run
/// names it, its size and its own bytes, which started again at 0 after the first file.
#[tokio::test]
async fn the_file_at_work_moves_while_it_is_hashed() {
    let (root, _) = test_support::local();
    let big = 3 * crate::BUFFER_SIZE as u64;
    test_support::write(root.path(), "a.bin", &test_support::pattern(1_000));
    test_support::write(
        root.path(),
        "b.bin",
        &test_support::pattern(3 * crate::BUFFER_SIZE),
    );
    let control = Control::new();
    let vfs: Arc<dyn Vfs> = Arc::new(test_support::Tripwire {
        inner: rc_vfs::LocalFs::new(),
        control: control.clone(),
        after: crate::BUFFER_SIZE as u64,
    });
    let error = create(
        &vfs,
        root.path(),
        &names(&["a.bin", "b.bin"]),
        Algorithm::Sha256,
        &Layout::PerFile,
        &control,
    )
    .await
    .expect_err("cancelled in the second file");
    assert_eq!(error.code(), "cancelled");
    assert_eq!(control.current_file(), Some(root.path().join("b.bin")));
    assert_eq!(control.file_bytes_total(), big);
    let done = control.file_bytes_done();
    assert!(
        (crate::BUFFER_SIZE as u64..big).contains(&done),
        "half way: {done}"
    );
    assert_eq!(control.bytes_done(), 1_000 + done);
}
