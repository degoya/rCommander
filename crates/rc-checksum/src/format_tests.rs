use super::*;

const SHA256_ABC: &str = "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad";

fn line(name: &str, algorithm: Algorithm, hex: &str) -> Option<ChecksumLine> {
    Some(ChecksumLine {
        name: name.to_owned(),
        algorithm,
        hex: hex.to_owned(),
    })
}

#[test]
fn the_gnu_form_is_read_in_binary_and_text_mode() {
    let text = format!("{SHA256_ABC} *a.txt\n{SHA256_ABC}  b c.txt\r\n");
    assert_eq!(
        parse_checksums(&text, None),
        vec![
            (1, line("a.txt", Algorithm::Sha256, SHA256_ABC)),
            (2, line("b c.txt", Algorithm::Sha256, SHA256_ABC)),
        ]
    );
}

#[test]
fn the_extension_breaks_the_tie_of_64_hex_digits() {
    let text = format!("{SHA256_ABC} *a\n");
    assert_eq!(
        parse_checksums(&text, Some(Algorithm::Blake3)),
        vec![(1, line("a", Algorithm::Blake3, SHA256_ABC))]
    );
    // A hint of another length does not bend a line: the content decides.
    let md5 = "900150983cd24fb0d6963f7d28e17f72";
    assert_eq!(
        parse_checksums(&format!("{md5} *a\n"), Some(Algorithm::Sha256)),
        vec![(1, line("a", Algorithm::Md5, md5))]
    );
}

#[test]
fn the_bsd_form_names_its_algorithm() {
    let text = format!("SHA256 (dir/a (1).txt) = {}\n", SHA256_ABC.to_uppercase());
    assert_eq!(
        parse_checksums(&text, None),
        vec![(1, line("dir/a (1).txt", Algorithm::Sha256, SHA256_ABC))]
    );
}

#[test]
fn sfv_lines_and_comments_are_read() {
    let text = "; Generated by someone\n\nfile one.bin CBF43926\n#comment\nother\t352441c2\n";
    assert_eq!(
        parse_checksums(text, Some(Algorithm::Crc32)),
        vec![
            (3, line("file one.bin", Algorithm::Crc32, "cbf43926")),
            (5, line("other", Algorithm::Crc32, "352441c2")),
        ]
    );
    // Without the extension the content still says SFV.
    assert_eq!(
        parse_checksums("file.bin CBF43926\n", None),
        vec![(1, line("file.bin", Algorithm::Crc32, "cbf43926"))]
    );
}

#[test]
fn escaped_names_are_unescaped() {
    let text = format!("\\{SHA256_ABC} *a\\\\b\\nc\n");
    assert_eq!(
        parse_checksums(&text, None),
        vec![(1, line("a\\b\nc", Algorithm::Sha256, SHA256_ABC))]
    );
    // An unknown escape makes the line unreadable rather than guessed.
    assert_eq!(
        parse_checksums(&format!("\\{SHA256_ABC} *a\\qb\n"), None),
        vec![(1, None)]
    );
}

#[test]
fn malformed_lines_are_numbered_not_dropped() {
    let text = "\u{feff}not a checksum\nxyz *file\n12345 *odd length\n";
    assert_eq!(
        parse_checksums(text, None),
        vec![(1, None), (2, None), (3, None)]
    );
}

#[test]
fn written_lines_read_back() {
    for algorithm in Algorithm::ALL {
        let mut hasher = algorithm.hasher();
        hasher.update(b"abc");
        let hex = hasher.finish_hex();
        for name in ["a.txt", "sub/with space.iso", "back\\slash", "line\nbreak"] {
            if algorithm == Algorithm::Crc32 && name.contains('\n') {
                continue; // SFV has no escaping; such a name has no SFV line.
            }
            let text = format!(
                "{}{}",
                sfv_header(algorithm),
                sum_line(algorithm, &hex, name)
            );
            let parsed = parse_checksums(&text, Some(algorithm));
            assert_eq!(parsed.len(), 1, "{algorithm:?} {name:?}: {text:?}");
            assert_eq!(parsed[0].1, line(name, algorithm, &hex), "{text:?}");
        }
    }
}

#[test]
fn the_written_forms_are_the_ones_the_tools_expect() {
    assert_eq!(
        sum_line(Algorithm::Sha256, SHA256_ABC, "a.txt"),
        format!("{SHA256_ABC} *a.txt\n")
    );
    assert_eq!(
        sum_line(Algorithm::Md5, "900150983cd24fb0d6963f7d28e17f72", "a\\b"),
        "\\900150983cd24fb0d6963f7d28e17f72 *a\\\\b\n"
    );
    assert_eq!(
        sum_line(Algorithm::Crc32, "cbf43926", "a b.bin"),
        "a b.bin CBF43926\n"
    );
    assert_eq!(sfv_header(Algorithm::Sha256), "");
    assert!(sfv_header(Algorithm::Crc32).starts_with(';'));
}
