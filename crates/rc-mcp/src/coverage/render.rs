//! Reading the coverage table: the command a tool wraps, and the page
//! `crates/rc-mcp/mcp-coverage.md`.

use std::fmt::Write as _;

use rc_engine::{COMMANDS, escalation};

use super::{COVERAGE, Coverage};

/// The command id a tool wraps.
#[must_use]
pub fn command_of(tool: &str) -> Option<&'static str> {
    COVERAGE
        .iter()
        .find(|(_, coverage)| matches!(coverage, Coverage::Covered(covered) if *covered == tool))
        .map(|(id, _)| *id)
}

/// The page `crates/rc-mcp/mcp-coverage.md`, exactly as `scripts/mcp-coverage.sh` writes it.
#[must_use]
pub fn render_markdown() -> String {
    let mut page = String::from(
        "# MCP coverage\n\
         \n\
         Generated by `scripts/mcp-coverage.sh` from `COMMANDS` (the groups of\n\
         `crates/rc-engine/src/registry.rs`) and the rows of `crates/rc-mcp/src/coverage/`;\n\
         do not edit by hand. Every engine command is either covered by an MCP tool or omitted\n\
         with a reason (`crates/rc-mcp/tests/mcp_coverage.rs`). The class is the command's; in\n\
         brackets the stricter class a call has when its parameters or what is stored make it so\n\
         (`ESCALATIONS` in `crates/rc-engine/src/registry/escalation.rs`), the one the MCP gate\n\
         asks by.\n\
         \n\
         | Command | Class | MCP tool | Summary |\n\
         | --- | --- | --- | --- |\n",
    );
    let (mut covered, mut omitted) = (0, 0);
    for spec in COMMANDS {
        let tool = match COVERAGE.iter().find(|(id, _)| *id == spec.id) {
            Some((_, Coverage::Covered(tool))) => {
                covered += 1;
                format!("`{tool}`")
            }
            Some((_, Coverage::Omitted(reason))) => {
                omitted += 1;
                format!("omitted: {reason}")
            }
            None => "**missing**".to_owned(),
        };
        let class = match escalation(spec.id) {
            Some(row) => format!(
                "{} ({} when {})",
                spec.class.as_str(),
                row.class.as_str(),
                row.when
            ),
            None => spec.class.as_str().to_owned(),
        };
        let _ = writeln!(
            page,
            "| `{}` | {class} | {tool} | {} |",
            spec.id, spec.summary
        );
    }
    let _ = writeln!(
        page,
        "\n{} commands: {covered} covered, {omitted} omitted.",
        COMMANDS.len()
    );
    page
}
