/// The language a fenced block's info string names by its first word (```` ```rust ````,
/// ```` ```sh title="x" ````, ```` ```{.python} ````); `None` for any other.
pub fn lang_of(info: &str) -> Option<&'static Lang> {
    let first = info
        .split(|c: char| c.is_whitespace() || c == ',' || c == '{' || c == '}')
        .find(|word| !word.is_empty())?;
    let tag = first.trim_start_matches('.').to_ascii_lowercase();
    Some(match tag.as_str() {
        "rust" | "rs" => &RUST,
        "json" | "jsonc" | "json5" => &JSON,
        "yaml" | "yml" => &YAML,
        "toml" => &TOML,
        "ini" | "cfg" | "conf" | "properties" | "editorconfig" | "gitconfig" => &INI,
        "sh" | "bash" | "shell" | "zsh" | "console" | "shellsession" => &SHELL,
        "python" | "py" | "python3" => &PYTHON,
        "js" | "javascript" | "jsx" | "mjs" | "cjs" | "ts" | "typescript" | "tsx" => &SCRIPT,
        "sql" | "mysql" | "postgresql" | "postgres" | "sqlite" => &SQL,
        "c" | "h" | "cpp" | "c++" | "cc" | "cxx" | "hpp" => &C,
        "ps1" | "powershell" | "pwsh" | "psm1" => &POWERSHELL,
        "xml" | "html" | "htm" | "xhtml" | "svg" => &MARKUP,
        "diff" | "patch" => &DIFF,
        _ => return None,
    })
}
