/// Whether an HTML attribute named `name` holds an event's JavaScript: `on` and more.
pub(super) fn is_event(name: &[u8]) -> bool {
    name.len() > 2
        && name
            .get(..2)
            .is_some_and(|head| head.eq_ignore_ascii_case(b"on"))
}
