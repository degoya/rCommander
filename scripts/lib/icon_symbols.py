"""The symbol collection of own commands and bar buttons (RC-110-10).

Writes crates/rcommander/resources/icons/rcommander-symbols.ttf, a second, larger subset of Fluent
UI System Icons' regular font (MIT) under the family name "rCommander Symbols", and the table the
code reads it by, crates/rc-engine/src/user_commands/symbols.tsv: one symbol a line - its name,
its code point, its category and its keywords - in the order of the list, scripts/lib/icon_symbols.txt.
`--check` holds the list, the table and the font's size to each other without the network or
fontTools; the Rust tests hold the table and the font's glyphs together.

    python3 scripts/lib/icon_symbols.py --write <FluentSystemIcons-Regular.ttf> <its .json> \\
        <list.txt> <out.ttf> <out.tsv>
    python3 scripts/lib/icon_symbols.py --check <list.txt> <table.tsv> <font.ttf>

Exit 0 when written or in step; 1 when --check finds the three apart; 2 for a list that does not
read (a line without a category and a name, an unknown category, a name twice or not upstream).
"""

import json
import os
import re
import sys

FAMILY = "rCommander Symbols"
POSTSCRIPT = "rCommanderSymbols-Regular"
CATEGORIES = (
    "files",
    "edit",
    "tools",
    "network",
    "development",
    "media",
    "system",
    "arrows",
    "status",
)
# The font's budget (the job file): 400 KiB.
MAX_FONT_BYTES = 400 * 1024
SUFFIX = "_20_regular"
NAME = re.compile(r"^[a-z0-9_]{1,64}$")
KEYWORD = re.compile(r"^[a-z0-9-]{1,32}$")
HEADER = (
    "# Generated by scripts/icon-font.sh --symbols from scripts/lib/icon_symbols.txt; "
    "never edited by hand.\n"
    "# name\tcode point\tcategory\tkeywords\n"
)


class ListError(Exception):
    """A line of the list that does not read."""


def read_list(path: str) -> list[tuple[str, str, str]]:
    """The list's rows: (name, category, keywords separated by blanks)."""
    rows = []
    seen = set()
    with open(path, encoding="utf-8") as file:
        for number, line in enumerate(file, 1):
            words = line.split()
            if not words or words[0].startswith("#"):
                continue
            if len(words) < 2:
                raise ListError(f"{path}:{number}: a category and a name")
            category, name, keywords = words[0], words[1], words[2:]
            if category not in CATEGORIES:
                raise ListError(f"{path}:{number}: no category {category!r}")
            if not NAME.match(name) or name in seen:
                raise ListError(f"{path}:{number}: {name!r} is no name or listed twice")
            bad = [word for word in keywords if not KEYWORD.match(word)]
            if bad:
                raise ListError(f"{path}:{number}: keywords in lower case: {' '.join(bad)}")
            seen.add(name)
            rows.append((name, category, " ".join(keywords)))
    return rows


def read_table(path: str) -> list[tuple[str, int, str, str]]:
    """The table's rows: (name, code point, category, keywords)."""
    rows = []
    with open(path, encoding="utf-8") as file:
        for line in file:
            if line.startswith("#") or not line.strip():
                continue
            fields = line.rstrip("\n").split("\t")
            if len(fields) != 4 or not fields[1].startswith("U+"):
                raise ListError(f"{path}: no row of four fields: {line.strip()!r}")
            rows.append((fields[0], int(fields[1][2:], 16), fields[2], fields[3]))
    return rows


def write(argv: list[str]) -> int:
    source, mapping, listed, font, table = argv
    from icon_font import subset_to

    rows = read_list(listed)
    with open(mapping, encoding="utf-8") as file:
        points = json.load(file)
    missing = [name for name, _, _ in rows if f"ic_fluent_{name}{SUFFIX}" not in points]
    if missing:
        raise ListError(f"not in the source: {', '.join(missing)}")
    unicodes = [points[f"ic_fluent_{name}{SUFFIX}"] for name, _, _ in rows]
    subset_to(source, unicodes, font, FAMILY, POSTSCRIPT)
    with open(table, "w", encoding="utf-8", newline="\n") as file:
        file.write(HEADER)
        for (name, category, keywords), point in zip(rows, unicodes):
            file.write(f"{name}\tU+{point:04X}\t{category}\t{keywords}\n")
    print(f"{len(rows)} symbols, {os.path.getsize(font)} bytes: {font}")
    return 0


def check(argv: list[str]) -> int:
    listed, table, font = argv
    rows = read_list(listed)
    written = read_table(table)
    wrong = []
    if [(name, category, keywords) for name, _, category, keywords in written] != rows:
        wrong.append(f"{table} is not the table of {listed}")
    points = [point for _, point, _, _ in written]
    if len(set(points)) != len(points):
        wrong.append(f"{table} gives two symbols one code point")
    size = os.path.getsize(font)
    if size > MAX_FONT_BYTES:
        wrong.append(f"{font} has {size} bytes, more than {MAX_FONT_BYTES}")
    for line in wrong:
        print(f"!! {line}; run scripts/icon-font.sh --symbols", file=sys.stderr)
    return 1 if wrong else 0


def main(argv: list[str]) -> int:
    try:
        if len(argv) == 7 and argv[1] == "--write":
            return write(argv[2:])
        if len(argv) == 5 and argv[1] == "--check":
            return check(argv[2:])
    except (ListError, OSError, ValueError) as error:
        print(f"!! {error}", file=sys.stderr)
        return 2
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
