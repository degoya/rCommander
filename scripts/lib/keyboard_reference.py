"""The wiki's keyboard reference, reference/keyboard-shortcuts.md, written from the keymap data.

The sources are read without compiling: the keymap (crates/rc-engine/keymap/default.json), the
names of its rows (the `keys.` entries of crates/rcommander/locales/en.json, which the command
palette shows too), how each command without a key is reached (reach.json of the palette), the
comparison with Total Commander (crates/rc-engine/keymap/tc.json), the registry's commands and
summaries (read as scripts/lib/mcp_coverage.py reads them) and the keys inside dialogs, which
crates/rc-engine/keymap/contexts.md keeps by hand. The Rust tests hold the same data against the compiled
keymap and registry (keymap_window_tests, keymap_tc_tests, palette/reach_tests, palette_tests),
so the page cannot name a key the program does not have.

    python3 scripts/lib/keyboard_reference.py <repo root> <wiki dir> [--check]

Exit 0 when written (or, with --check, current or no wiki to check); 1 when --check finds the
page stale; 2 when the data does not fit: a command without a key and without a reach row, a
row for a command with a key or for none, a name without its words, a file that does not read.
"""

import json
import sys
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
import mcp_coverage  # noqa: E402

KEYMAP = "crates/rc-engine/keymap/default.json"
TC = "crates/rc-engine/keymap/tc.json"
REACH = "crates/rcommander/src/app/palette/reach.json"
CATALOGUE = "crates/rcommander/locales/en.json"
CONTEXTS = "crates/rc-engine/keymap/contexts.md"
PAGE = "reference/keyboard-shortcuts.md"

HEADER = """# Keyboard shortcuts

> Generated by `scripts/keyboard-reference.sh` from rCommander's keymap
> (`crates/rc-engine/keymap/`, the keys inside dialogs in its `contexts.md`) and the command
> registry; do not edit by hand. It cannot drift from what the program does: the same data is the
> program's keymap.

rCommander replaces Total Commander (TC) for its owner, so its default keys are **Total
Commander 11's**. The keys rCommander has of its own, the ones that do something else than in TC
and the TC keys it leaves free are listed with their reasons under
[Total Commander](#total-commander). **Ctrl+Shift+P** opens the command palette: every action by
name, also the ones without a key.

These are the standard keys. **Settings > Keyboard > Shortcuts** changes, adds or removes any of
them; the menus, the context menus and the command palette then show your keys.
"""


class DataError(ValueError):
    """The data does not fit together."""


def chord(text: str) -> str:
    """A chord as the program prints it (`keymap.rs`, `Display for Chord`): Ctrl, Shift, Alt,
    then the key, one character in upper case."""
    modifiers, _, key = text.rpartition("+")
    held = {part.lower() for part in modifiers.split("+") if part}
    if not key:
        raise DataError(f"{text!r} is not a chord")
    unknown = held - {"ctrl", "shift", "alt"}
    if unknown:
        raise DataError(f"{text!r}: unknown modifier {sorted(unknown)}")
    names = [name for name in ("Ctrl", "Shift", "Alt") if name.lower() in held]
    return "+".join(names + [key.upper() if len(key) == 1 else key])


def cell(text: str) -> str:
    """`text` safe in a table cell."""
    return text.replace("\\", "\\\\").replace("`", "\\`").replace("|", "\\|")


def keys_cell(chords: list[str]) -> str:
    return ", ".join(cell(chord_text) for chord_text in chords)


def load(root: Path, name: str):
    try:
        return json.loads((root / name).read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        raise DataError(f"{name}: {error}") from error


def label(names: dict, name: str) -> str:
    key = f"keys.{name}"
    if key not in names:
        raise DataError(f"{CATALOGUE}: no {key}")
    return names[key]


def rows_by_name(keymap: list, names: dict) -> list[dict]:
    """The keymap's commands and window keys, one row per name in the order written."""
    rows: list[dict] = []
    for row in keymap:
        if "command" in row:
            name, what = row.get("name", row["command"]), f"`{row['command']}`"
        elif "window" in row:
            name, what = row["window"], "window"
        else:
            continue
        keys = chord(row["keys"])
        always = row.get("when") == "always"
        known = next((known for known in rows if known["name"] == name), None)
        if known:
            known["keys"].append(keys)
            known["always"] = known["always"] or always
        else:
            rows.append(
                {"name": name, "keys": [keys], "what": what, "label": label(names, name), "always": always}
            )
    return rows


def sentence(text: str) -> str:
    """`text` with a capital first letter, safe in a table cell."""
    return cell(text[:1].upper() + text[1:])


def reach_text(row: dict, names: dict) -> str:
    """How the keyboard reaches a command without a key, as a table cell."""
    if row.get("palette"):
        return f"Command palette: *{cell(label(names, row['command']))}*"
    if "via" in row:
        target = row["via"]
        if target.startswith("window:"):
            return sentence(row["how"])
        return f"{sentence(row['how'])} (`{target}`)"
    for kind, lead in (("asked", "Asked"), ("shown", "Shown"), ("omitted", "No key")):
        if kind in row:
            return f"{lead}: {cell(row[kind])}"
    raise DataError(f"{REACH}: {row['command']}: say one way it is reached")


def check_reach(specs: list, keymap: list, reach: list) -> None:
    ids = [spec[0] for spec in specs]
    bound = {row["command"] for row in keymap if "command" in row}
    listed = [row["command"] for row in reach]
    problems = [f"{id_} has no key and no row in {REACH}" for id_ in ids if id_ not in bound and id_ not in listed]
    problems += [f"{id_} has a key: drop its row from {REACH}" for id_ in listed if id_ in bound]
    problems += [f"{id_} is not a command of the registry" for id_ in listed if id_ not in ids]
    problems += [f"{id_} has two rows in {REACH}" for id_ in set(listed) if listed.count(id_) > 1]
    if problems:
        raise DataError("; ".join(sorted(problems)))


def contexts(root: Path) -> str:
    """crates/rc-engine/keymap/contexts.md without its leading comment."""
    try:
        text = (root / CONTEXTS).read_text(encoding="utf-8")
    except OSError as error:
        raise DataError(f"{CONTEXTS}: {error}") from error
    if text.startswith("<!--"):
        text = text[text.index("-->") + 3 :]
    return text.strip() + "\n"


def render(root: Path) -> str:
    keymap = load(root, KEYMAP)
    names = load(root, CATALOGUE)
    reach = load(root, REACH)
    tc = load(root, TC)
    specs = mcp_coverage.commands(root)
    summaries = {spec[0]: spec[2] for spec in specs}
    check_reach(specs, keymap, reach)

    page = HEADER
    page += "\n## Keys of the panels\n\n"
    page += "While the active panel shows its files; a terminal keeps every key but the ones marked.\n"
    page += "*window* is a key the window handles itself (the command line, the palette, a connection).\n\n"
    page += "| Key | Action | Command |\n| --- | --- | --- |\n"
    rows = rows_by_name(keymap, names)
    for row in rows:
        action = cell(row["label"]) + (" (also in a terminal)" if row["always"] else "")
        page += f"| {keys_cell(row['keys'])} | {action} | {row['what']} |\n"

    reserved = [row for row in keymap if "reserved" in row]
    if reserved:
        page += "\n## Reserved keys\n\nKept free for the job that brings their Total Commander feature.\n\n"
        page += "| Key | Kept for |\n| --- | --- |\n"
        for row in reserved:
            page += f"| {cell(chord(row['keys']))} | {cell(row['reserved'])} |\n"

    page += "\n## Commands without a key\n\n"
    page += "Every command of the registry has a key above, or a row here that says how the keyboard\n"
    page += "reaches it - or why not (`crates/rcommander/src/app/palette/reach.json`).\n\n"
    page += "| Command | How | Summary |\n| --- | --- | --- |\n"
    order = {spec[0]: at for at, spec in enumerate(specs)}
    for row in sorted(reach, key=lambda row: order[row["command"]]):
        page += f"| `{row['command']}` | {reach_text(row, names)} | {cell(summaries[row['command']])} |\n"
    bound = len({row["command"] for row in keymap if "command" in row})
    counts = {kind: sum(1 for row in reach if kind in row) for kind in ("palette", "via", "asked", "shown", "omitted")}
    page += (
        f"\n{len(specs)} commands: {bound} with a key, {counts['palette']} in the command palette, "
        f"{counts['via']} in a dialog, {counts['asked']} asked by the window, {counts['shown']} shown "
        f"by it, {counts['omitted']} without a way in, each for the reason it gives.\n"
    )

    page += "\n## Total Commander\n\n"
    page += "Every other key above does what it does in Total Commander 11, as far as TC's own\n"
    page += "documentation records its keys (its `KEYBOARD.TXT` ships only inside its installer).\n"
    page += "The table is `crates/rc-engine/keymap/tc.json`; a test holds it against the keymap.\n\n"
    by_kind = {kind: [row for row in tc if row["kind"] == kind] for kind in ("own", "differs", "free")}
    known = {row["kind"] for row in tc} - set(by_kind)
    if known:
        raise DataError(f"{TC}: unknown kinds {sorted(known)}")
    page += "### rCommander's own keys\n\n| Key | Why |\n| --- | --- |\n"
    for row in by_kind["own"]:
        page += f"| {cell(chord(row['keys']))} | {sentence(row['why'])} |\n"
    page += "\n### Keys that do more or something else than in TC\n\n| Key | TC | Why |\n| --- | --- | --- |\n"
    for row in by_kind["differs"]:
        page += f"| {cell(chord(row['keys']))} | {sentence(row['tc'])} | {sentence(row['why'])} |\n"
    page += "\n### TC keys left free\n\n| Key | TC | Why |\n| --- | --- | --- |\n"
    for row in by_kind["free"]:
        page += f"| {cell(chord(row['keys']))} | {sentence(row['tc'])} | {sentence(row['why'])} |\n"

    page += "\n" + contexts(root)
    return page


def main(argv: list[str]) -> int:
    if len(argv) < 3 or any(arg != "--check" for arg in argv[3:]):
        print("usage: keyboard_reference.py <repo root> <wiki dir> [--check]", file=sys.stderr)
        return 2
    root, wiki = Path(argv[1]), Path(argv[2])
    check = "--check" in argv[3:]
    try:
        page = render(root)
    except (DataError, OSError, ValueError, KeyError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 2
    target = wiki / PAGE
    if not wiki.is_dir():
        if check:
            print(f"==> no wiki at {wiki}: the keymap data fits, the page is not checked")
            return 0
        print(f"error: no wiki at {wiki} (set RC_WIKI)", file=sys.stderr)
        return 2
    current = target.read_text(encoding="utf-8") if target.exists() else None
    if check:
        if current != page:
            print(f"{target} is stale: run scripts/keyboard-reference.sh", file=sys.stderr)
            return 1
        print(f"==> {target} is current")
        return 0
    if current == page:
        print(f"==> {target} was already current")
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(page, encoding="utf-8")
        print(f"==> wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
