"""The licence texts of the shipped crates: crates/rcommander/resources/licenses/THIRD-PARTY-LICENSES.

MIT, BSD and ISC want their notice in a binary copy, Apache-2.0 a copy of the licence (RC-110-72).
Each crate's texts are the licence files at the top of its source as cargo unpacked it (the
directory of its `manifest_path` in `cargo metadata`): every file named LICENSE*, LICENCE*,
COPYING*, COPYRIGHT*, NOTICE* or UNLICENSE*, the files of a REUSE `LICENSES/` folder, and the
file `license-file` names. A crate whose archive carries none takes them from its entry in
crates/rcommander/resources/licenses/overrides.json:

- `"texts_from": "<name>@<version>"`, a locked crate of the same repository whose files apply
  (iced's for iced_core);
- `"standard": "<SPDX id>"`, the standard text in crates/rcommander/resources/licenses/texts/,
  one the crate's licence expression names; MIT's gets the copyright line from the crate's
  `authors` (or the entry's `"copyright"`).

Each distinct text is written once, headed by the crates it covers. Line ends, trailing blanks,
form feeds and a byte-order mark are dropped, so two copies of a licence that differ only there
are one text. `parse` reads the file back (scripts/lib/license_dep5.py; the About page has its own
reader in crates/rcommander/src/app/settings/about/license_texts.rs, which this layout binds).
"""

import os
import re
from pathlib import Path

TEXTS = "crates/rcommander/resources/licenses/THIRD-PARTY-LICENSES"
STANDARD = "crates/rcommander/resources/licenses/texts"
# Opens a text's block; the header lines below it name the crates, BODY ends them. No text may
# hold a line that starts as either does (`=== Licence `, `--- Text `): the readers split there.
BLOCK = "=== Licence " + "=" * 68
BODY = "--- Text " + "-" * 71
FILE_NAME = re.compile(r"^(licen[cs]e|copying|copyright|notice|unlicense)", re.IGNORECASE)
EMAIL = re.compile(r"\s*<[^>]*>")

PREAMBLE = """\
Third-party licences of rCommander
==================================

rCommander is free software under the GNU General Public License, version 3 or later (LICENSE).
It contains the Rust crates below - those the program links on Windows, Linux and macOS and those
the bundled plugins (plugins/*.rcplug) compile in - and the further third-party material NOTICE
names. Each licence text follows once, headed by the crates it covers, one per line:

    <crate> <version> (<the licence the crate declares>): <where the text was read>

A crate offered under a choice of licences lists every text its archive carries; the choice
stays yours. A crate whose archive carries no licence file is given the files of a crate from
the same repository, or the standard text of its licence, and says so.

The source of every crate is published at https://crates.io/crates/<crate>/<version>, the source
of rCommander at https://github.com/degoya/rCommander.

Generated by scripts/licenses.sh from the crates' own files; never edited by hand.
"""


def normalise(raw: bytes) -> str:
    """The text of a licence file without the bytes that differ between copies of one licence."""
    try:
        text = raw.decode("utf-8-sig")
    except UnicodeDecodeError:
        text = raw.decode("latin-1")
    text = text.replace("\r\n", "\n").replace("\r", "\n").replace("\f", "")
    return "\n".join(line.rstrip() for line in text.split("\n")).strip("\n")


def crate_files(directory: Path, license_file: str | None) -> list[tuple[str, Path]]:
    """The licence files of a crate's source: (the name to show, the path), by name."""
    found: list[tuple[str, Path]] = []
    try:
        entries = sorted(os.listdir(directory))
    except OSError:
        return []
    for entry in entries:
        if not FILE_NAME.match(entry):
            continue
        path = directory / entry
        if path.is_file():
            found.append((entry, path))
        elif path.is_dir():
            found.extend((f"{entry}/{inner}", path / inner) for inner in sorted(os.listdir(path)) if (path / inner).is_file())
    if license_file:
        path = directory / license_file
        if path.is_file() and all(path.resolve() != known.resolve() for _, known in found):
            found.append((license_file, path))
    return found


def _names(expression: str, identifier: str) -> bool:
    """Whether an SPDX expression names `identifier` as one of its licences."""
    return re.search(rf"(?<![\w.+-]){re.escape(identifier)}(?![\w.+-])", expression) is not None


def texts_of(key: str, package: dict, locked: dict, override: dict, expression: str, root: Path) -> tuple[list, str | None]:
    """[(where it was read, the text)] for crate `key`, or the reason there is none."""
    files = crate_files(Path(package["manifest_path"]).parent, package.get("license_file"))
    source, standard = override.get("texts_from"), override.get("standard")
    if files:
        if source or standard:
            return [], f"{key}: its archive carries licence files; drop texts_from/standard from its override"
        return [(name, normalise(path.read_bytes())) for name, path in files], None
    if source:
        other = locked.get(source)
        if other is None:
            return [], f"{key}: texts_from names {source}, which is not locked"
        files = crate_files(Path(other["manifest_path"]).parent, other.get("license_file"))
        if not files:
            return [], f"{key}: texts_from names {source}, whose archive carries no licence file either"
        where = f"of {other['name']} {other['version']}, the crate's archive carries none"
        return [(f"{name} {where}", normalise(path.read_bytes())) for name, path in files], None
    if standard:
        if not _names(expression, standard):
            return [], f"{key}: standard {standard} is not a licence of '{expression}'"
        path = root / STANDARD / f"{standard}.txt"
        if not path.is_file():
            return [], f"{key}: no standard text {STANDARD}/{standard}.txt"
        text = normalise(path.read_bytes())
        if standard == "MIT":
            holders = override.get("copyright") or ", ".join(EMAIL.sub("", author).strip() for author in package.get("authors") or [])
            if not holders:
                return [], f"{key}: MIT wants a copyright line; the crate names no authors, record \"copyright\""
            text = f"Copyright (c) {holders}\n\n{text}"
        return [(f"the standard {standard} text, the crate's archive carries no licence file", text)], None
    return [], f"{key}: its archive carries no licence file; record texts_from or standard"


def render(entries: list[tuple[str, str, list]]) -> tuple[str, list[str]]:
    """The file's text from (`name version`, licence, texts) per crate, and what does not fit."""
    covers: dict[str, list[str]] = {}
    for crate, expression, texts in entries:
        for where, text in texts:
            covers.setdefault(text, []).append(f"{crate} ({expression}): {where}")
    problems = []
    blocks = []
    for text, headers in covers.items():
        if not text:
            problems.append(f"{headers[0]}: an empty licence file")
            continue
        if any(line.startswith((BLOCK[:12], BODY[:9])) for line in text.split("\n")):
            problems.append(f"{headers[0]}: the text holds a separator line")
            continue
        blocks.append((sorted(headers), text))
    blocks.sort(key=lambda block: block[0][0])
    count = f"Crates: {len(entries)}. Distinct licence texts: {len(blocks)}.\n"
    parts = [PREAMBLE, "\n", count]
    for headers, text in blocks:
        parts.append(f"\n{BLOCK}\n" + "\n".join(headers) + f"\n{BODY}\n{text}\n")
    return "".join(parts), problems


def parse(text: str) -> list[tuple[list[str], str]]:
    """The file's blocks: the header lines (one per crate) and the licence text."""
    blocks = []
    for chunk in text.split(f"\n{BLOCK}\n")[1:]:
        headers, _, body = chunk.partition(f"\n{BODY}\n")
        blocks.append((headers.split("\n"), body.rstrip("\n")))
    return blocks
