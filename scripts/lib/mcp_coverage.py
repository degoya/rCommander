"""The MCP coverage page, crates/rc-mcp/mcp-coverage.md, written from the Rust tables without
compiling.

The sources are the command groups of crates/rc-engine/src/registry.rs (`command_groups!`, in
the order `COMMANDS` assembles them, each group's `COMMANDS` table in registry/<group>.rs), the
`ESCALATIONS` table of registry/escalation.rs and the `ROWS`
table of every file in crates/rc-mcp/src/coverage/, read with regular expressions; the files keep their rows in the
shape their module comments name. The page is the same text `rc_mcp::coverage::render_markdown`
builds, and crates/rc-mcp/tests/mcp_coverage.rs fails when the two differ - so a parser that
misreads a row cannot go unnoticed.

    python3 scripts/lib/mcp_coverage.py <repo root> [--check]

Exit 0 when written (or, with --check, current); 1 when --check finds the page stale; 2 when a
command has no coverage row, a row names an unknown command, or a table cannot be read.
"""

import re
import sys
from pathlib import Path

REGISTRY = "crates/rc-engine/src/registry.rs"
GROUP_DIR = "crates/rc-engine/src/registry"
COVERAGE_DIR = "crates/rc-mcp/src/coverage"
PAGE = "crates/rc-mcp/mcp-coverage.md"

SPEC = re.compile(
    r'CommandSpec\s*\{\s*id:\s*"([^"]+)",\s*class:\s*CommandClass::(\w+),'
    r'\s*summary:\s*"([^"]*)",?\s*\}'
)
GROUPS = "macro_rules! command_groups"
GROUP = re.compile(r"^\s*(\w+),$", re.M)
ROW = re.compile(r'\(\s*"([^"]+)",\s*Coverage::(Covered|Omitted)\(\s*"([^"]*)",?\s*\),?\s*\)')
ESCALATIONS = "crates/rc-engine/src/registry/escalation.rs"
ESCALATION = re.compile(
    r'Escalation\s*\{\s*id:\s*"([^"]+)",\s*class:\s*CommandClass::(\w+),'
    r'\s*when:\s*"([^"]*)",?\s*\}'
)

HEADER = """# MCP coverage

Generated by `scripts/mcp-coverage.sh` from `COMMANDS` (the groups of
`crates/rc-engine/src/registry.rs`) and the rows of `crates/rc-mcp/src/coverage/`;
do not edit by hand. Every engine command is either covered by an MCP tool or omitted
with a reason (`crates/rc-mcp/tests/mcp_coverage.rs`). The class is the command's; in
brackets the stricter class a call has when its parameters or what is stored make it so
(`ESCALATIONS` in `crates/rc-engine/src/registry/escalation.rs`), the one the MCP gate
asks by.

| Command | Class | MCP tool | Summary |
| --- | --- | --- | --- |
"""


def table(path: Path, start: str) -> str:
    """The text of the `const` named by `start`, up to its closing `];`."""
    text = path.read_text(encoding="utf-8")
    begin = text.find(start)
    end = text.find("];", begin)
    if begin < 0 or end < 0:
        raise ValueError(f"{path}: no `{start}` table")
    return text[begin:end]


def group_list(path: Path) -> list[str]:
    """The groups of `command_groups!`, one per line up to the list's closing `]`."""
    text = path.read_text(encoding="utf-8")
    begin = text.find(GROUPS)
    list_start = text.find("[", begin)
    end = text.find("]", list_start)
    if begin < 0 or list_start < 0 or end < 0:
        raise ValueError(f"{path}: no `{GROUPS}` list")
    return GROUP.findall(text[list_start:end])


def class_name(variant: str) -> str:
    """`CommandClass::GuiOnly` as `CommandClass::as_str` spells it: `gui_only`."""
    return re.sub(r"(?<!^)(?=[A-Z])", "_", variant).lower()


def commands(root: Path) -> list[tuple[str, str, str]]:
    """The rows of `COMMANDS`: each group of `command_groups!` in order, its table read from its
    module."""
    groups = group_list(root / REGISTRY)
    if not groups:
        raise ValueError(f"{REGISTRY}: no groups in command_groups!")
    specs = []
    for group in groups:
        rows = SPEC.findall(table(root / GROUP_DIR / f"{group}.rs", "pub(super) const COMMANDS"))
        if not rows:
            raise ValueError(f"{GROUP_DIR}/{group}.rs: no CommandSpec rows found")
        specs += rows
    return specs


def coverage(root: Path) -> dict[str, tuple[str, str]]:
    """The coverage rows: the `ROWS` table of every file in the coverage directory."""
    rows: dict[str, tuple[str, str]] = {}
    for path in sorted((root / COVERAGE_DIR).glob("*.rs")):
        if "const ROWS" not in path.read_text(encoding="utf-8"):
            continue
        for command, how, detail in ROW.findall(table(path, "const ROWS")):
            if command in rows:
                raise ValueError(f"{command}: two coverage rows")
            rows[command] = (how, detail)
    if not rows:
        raise ValueError(f"{COVERAGE_DIR}: no coverage rows found")
    return rows


def escalations(root: Path) -> dict[str, tuple[str, str]]:
    """The rows of `ESCALATIONS`: the stricter class of a command's calls, and when."""
    found = ESCALATION.findall(table(root / ESCALATIONS, "pub const ESCALATIONS"))
    if not found:
        raise ValueError(f"{ESCALATIONS}: no Escalation rows found")
    return {command: (class_name(kind), when) for command, kind, when in found}


def render(root: Path) -> str:
    specs = commands(root)
    rows = coverage(root)
    stricter = escalations(root)
    if not specs:
        raise ValueError(f"{REGISTRY}: no CommandSpec rows found")
    ids = [spec[0] for spec in specs]
    missing = [command for command in ids if command not in rows]
    unknown = [command for command in rows if command not in ids]
    if missing or unknown:
        raise ValueError(
            f"commands without a coverage row: {missing}; rows for unknown commands: {unknown}"
        )
    page = HEADER
    covered = omitted = 0
    for command, kind, summary in specs:
        how, detail = rows[command]
        if how == "Covered":
            covered += 1
            tool = f"`{detail}`"
        else:
            omitted += 1
            tool = f"omitted: {detail}"
        shown = class_name(kind)
        if command in stricter:
            escalated, when = stricter[command]
            shown += f" ({escalated} when {when})"
        page += f"| `{command}` | {shown} | {tool} | {summary} |\n"
    page += f"\n{len(specs)} commands: {covered} covered, {omitted} omitted.\n"
    return page


def main(argv: list[str]) -> int:
    if len(argv) < 2 or any(arg != "--check" for arg in argv[2:]):
        print("usage: mcp_coverage.py <repo root> [--check]", file=sys.stderr)
        return 2
    root = Path(argv[1])
    try:
        page = render(root)
    except (OSError, ValueError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 2
    target = root / PAGE
    current = target.read_text(encoding="utf-8") if target.exists() else None
    if "--check" in argv[2:]:
        if current != page:
            print(f"{PAGE} is stale: run scripts/mcp-coverage.sh", file=sys.stderr)
            return 1
        print(f"==> {PAGE} is current")
        return 0
    if current == page:
        print(f"==> {PAGE} was already current")
    else:
        target.write_text(page, encoding="utf-8")
        print(f"==> wrote {PAGE}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
