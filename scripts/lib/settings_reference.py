"""The wiki's settings reference, reference/settings.md, written from the settings schema.

The sources are read without compiling: `SETTINGS` in crates/rc-engine/src/settings/schema.rs is
the authority for which settings exist and in which order; each row is evaluated from the Rust
(settings_reference_rust.py), its constants and `const fn` helpers followed into
schema/<area>.rs and into other crates (rc_ops, rc_vault, rc_plugin_host). The words - label, help,
choices, page and tab titles - are crates/rcommander/locales/en.json's; the dialog's page order
and its Appearance tabs are the window's (app/settings.rs `Page::ALL`, settings/view.rs,
settings/tabs.rs `APPEARANCE`); what is protected beyond a row's flag is lookup.rs's prefixes. The
Rust tests hold the same data against the compiled program (settings tests, tabs_tests).

    python3 scripts/lib/settings_reference.py <repo root> <wiki dir> [--check]

Exit 0 when written (or, with --check, current or no wiki to check); 1 when --check finds the
page stale; 2 when the data does not read: a row the reader cannot evaluate (named), a count of
rows in the source that differs from what was read, a text missing from the catalogue, a page or
a kind the page does not know.
"""

import json
import re
import sys
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
from settings_reference_rust import Evaluator, Lexer, RustError, World  # noqa: E402

SCHEMA = "crates/rc-engine/src/settings/schema.rs"
LOOKUP = "crates/rc-engine/src/settings/schema/lookup.rs"
DIALOG = "crates/rcommander/src/app/settings.rs"
VIEW = "crates/rcommander/src/app/settings/view.rs"
TABS = "crates/rcommander/src/app/settings/tabs.rs"
CATALOGUE = "crates/rcommander/locales/en.json"
PAGE = "reference/settings.md"

HEADER = """# Settings

> Generated by `scripts/settings-reference.sh` from rCommander's settings schema
> (`crates/rc-engine/src/settings/`), the settings dialog's pages and its texts; do not edit by
> hand. It cannot drift from what the program does: the same rows are the program's settings.

Every setting of the settings dialog (**Configuration > Settings...**), page by page in the
dialog's order, with its key, the values it takes and its default. The key is the name an AI
assistant uses with the MCP tools `settings_get` and `settings_set` ([MCP server](mcp)), and the
name an exported settings file carries.

- **Protected**: only a person in the window changes it; `settings_set` refuses it for every
  caller, so an assistant never widens its own rights or chooses the programs and code that run.
- **Restart**: it takes effect the next time rCommander starts.
"""

# What each kind of value takes, by `SettingKind` variant; a variant missing here stops the page.
KINDS = {
    "Bool": "On or off",
    "Int": "A whole number from {min} to {max}",
    "Choice": "{choices}",
    "Id": "A short name: letters, digits, `.`, `_` and `-`",
    "Path": "An absolute path",
    "Font": "The name of an installed font",
    "Extensions": "File extensions without dots, separated by spaces",
    "Associations": "Pairs `extension=plugin id`, separated by spaces",
    "Keymap": "Pairs `key=command`, separated by spaces; `key=` takes a standard key away",
    "Colour": "A colour `#rrggbb`; empty for the look's own",
    "ColourRules": "Rules, one per line: a mask as for Num+, a tab, a colour `#rrggbb`, and a dark colour after another tab",
    "Source": "An `https://` folder serving the update manifests; empty for the official releases",
    "Proxy": "Empty for the system's proxy, `direct`, or `http(s)://host:port` without a login",
}

PLUGINS_NOTE = """
A plugin's own settings are declared in its manifest and stored as `plugin.<id>.<key>`,
protected like these; they are changed on the tab *{installed}* with the plugin selected. The
bundled viewers' settings are described in [Plugins](../using/plugins#the-bundled-viewers).
"""

KEYMAP_NOTE = "The standard keys: [Keyboard shortcuts](keyboard-shortcuts)."


class DataError(ValueError):
    """The data does not read or does not fit together."""


def read(root: Path, name: str) -> str:
    try:
        return (root / name).read_text(encoding="utf-8")
    except OSError as error:
        raise DataError(f"{name}: {error}") from error


def fn_body(text: str, name: str, where: str) -> str:
    """The body of `fn name` up to the first closing brace at the line's start."""
    match = re.search(r"\bfn " + re.escape(name) + r"\b.*?\n\}", text, re.S)
    if not match:
        raise DataError(f"{where}: no fn {name}")
    return match.group()


def variants(text: str, enum: str, where: str) -> list[str]:
    match = re.search(r"pub enum " + enum + r" \{(.*?)\n\}", text, re.S)
    if not match:
        raise DataError(f"{where}: no enum {enum}")
    body = re.sub(r"//[^\n]*", "", match.group(1))
    return re.findall(r"^\s*([A-Z]\w*)\s*(?:[,{]|$)", body, re.M)


def settings(root: Path) -> list[dict]:
    """`SETTINGS`, each row evaluated; a row that does not read is named."""
    world = World(root)
    try:
        schema = world.module(root / SCHEMA, "rc-engine")
    except (OSError, RustError) as error:
        raise DataError(f"{SCHEMA}: {error}") from error
    if "SETTINGS" not in schema.consts:
        raise DataError(f"{SCHEMA}: no SETTINGS")
    lexer = Lexer(schema, schema.place(schema.consts, "SETTINGS"))
    rows: list[dict] = []
    inline = 0
    try:
        lexer.skip_until("=")
        for token in ("=", "&", "["):
            lexer.expect(token)
    except RustError as error:
        raise DataError(f"{SCHEMA}: SETTINGS: {error}") from error
    while lexer.peek()[1] != "]":
        start = lexer.start
        source = schema.text[start : schema.text.find("\n", start)].strip().rstrip(",")
        if source.startswith("SettingSpec {"):
            inline += 1
            key = re.match(r"SettingSpec \{\s*key: ([^,\n]+)", schema.text[start:])
            source = f"SettingSpec {{ key: {key.group(1) if key else '?'} }}"
        try:
            rows.append({"source": source, **check_row(Evaluator(schema, {}).expr(lexer))})
            if not lexer.take(","):
                lexer.expect("]")
                break
        except (RustError, DataError, OSError) as error:
            raise DataError(f"SETTINGS entry {len(rows) + 1} ({source}): {error}") from error

    # Every spec of the source is a row: the constants of type SettingSpec in the area modules and
    # the literals written into SETTINGS. One defined but not listed, or a row read twice, differs.
    spec_const = re.compile(r"(?m)^\s*(?:pub(?:\([^)]*\))?\s+)?const \w+: SettingSpec =")
    areas = sorted((root / SCHEMA).with_suffix("").glob("*.rs"))
    consts = sum(len(spec_const.findall(path.read_text(encoding="utf-8"))) for path in areas)
    if consts + inline != len(rows):
        raise DataError(
            f"{SCHEMA}: the source has {consts + inline} settings ({consts} constants, {inline} "
            f"literals in SETTINGS), {len(rows)} were read from SETTINGS"
        )
    keys = [row["key"] for row in rows]
    twice = sorted({key for key in keys if keys.count(key) > 1})
    if twice:
        raise DataError(f"{SCHEMA}: keys listed twice: {', '.join(twice)}")
    return rows


def check_row(value: object) -> dict:
    """A `SettingSpec` value as the page needs it, or why it is not one."""
    if not isinstance(value, dict) or value.get("__type") != "SettingSpec":
        raise DataError(f"not a SettingSpec: {value!r}")
    fields = {"key": str, "label": str, "help": str, "protected": bool, "restart": bool}
    for field, kind in fields.items():
        if not isinstance(value.get(field), kind):
            raise DataError(f"{field} is {value.get(field)!r}")
    page, kind = value.get("page"), value.get("kind")
    if not (isinstance(page, tuple) and page[:2] == ("enum", "SettingPage")):
        raise DataError(f"page is {page!r}")
    if not (isinstance(kind, dict) and kind["__type"].startswith("SettingKind::")):
        raise DataError(f"kind is {kind!r}")
    variant = kind["__type"].removeprefix("SettingKind::")
    wanted = {"Bool": {"default": bool}, "Int": {"min": int, "max": int, "default": int}}
    wanted["Choice"] = {"choices": list, "default": str}
    for field, field_kind in wanted.get(variant, {"default": str}).items():
        got = kind.get(field)
        if not isinstance(got, field_kind) or (field_kind is int and isinstance(got, bool)):
            raise DataError(f"kind {variant}: {field} is {got!r}")
    if variant == "Int" and not kind["min"] <= kind["default"] <= kind["max"]:
        raise DataError(f"default {kind['default']} outside {kind['min']}..={kind['max']}")
    if variant == "Choice":
        values = [choice.get("value") for choice in kind["choices"]]
        if kind["default"] not in values:
            raise DataError(f"default {kind['default']!r} is no choice")
    return {**value, "page": page[2], "variant": variant}


def dialog(root: Path, pages: list[str]) -> list[tuple[str, str, str]]:
    """The dialog's pages in its order that show schema rows: (schema page, title key, page)."""
    order = re.search(r"const ALL: \[Self; \d+\] = \[(.*?)\];", read(root, DIALOG), re.S)
    if not order:
        raise DataError(f"{DIALOG}: no Page::ALL")
    view = read(root, VIEW)
    shown = dict(re.findall(r"Page::(\w+) => Some\(SettingPage::(\w+)\)", fn_body(view, "schema_page", VIEW)))
    titles = dict(re.findall(r'Page::(\w+) => t!\("([^"]+)"\)', fn_body(view, "page_title", VIEW)))
    result = []
    for page in re.findall(r"Self::(\w+)", order.group(1)):
        if page in shown:
            if page not in titles:
                raise DataError(f"{VIEW}: page_title has no Page::{page}")
            result.append((shown[page], titles[page], page))
    missing = sorted(set(pages) - {schema for schema, _, _ in result})
    if missing:
        raise DataError(f"{VIEW}: no dialog page shows SettingPage::{', '.join(missing)}")
    return result


def appearance_tabs(root: Path) -> tuple[list[tuple[str, list[str]]], dict[str, str]]:
    """The Appearance page's tabs in their order with their keys, and every tab's title key."""
    text = read(root, TABS)
    order = re.search(r"const APPEARANCE_TABS: \[Tab; \d+\] = \[(.*?)\];", text, re.S)
    table = re.search(r"pub const APPEARANCE: &\[\(Tab, &\[&str\]\)\] = &\[(.*?)\n\];", text, re.S)
    if not order or not table:
        raise DataError(f"{TABS}: no APPEARANCE_TABS or APPEARANCE")
    groups = re.findall(r"Tab::(\w+),\s*&\[(.*?)\]", table.group(1), re.S)
    keys = {tab: re.findall(r'"([^"]+)"', body) for tab, body in groups}
    titles = dict(re.findall(r'Tab::(\w+) => t!\("([^"]+)"\)', fn_body(text, "title", TABS)))
    return [(tab, keys.get(tab, [])) for tab in re.findall(r"Tab::(\w+)", order.group(1))], titles


def protected_prefixes(root: Path) -> list[str]:
    body = fn_body(read(root, LOOKUP), "is_protected", LOOKUP)
    match = re.search(r"\[((?:\s*\"[^\"]*\",?)+)\s*\]\s*\.iter\(\)", body)
    if not match:
        raise DataError(f"{LOOKUP}: is_protected has no list of prefixes")
    return re.findall(r'"([^"]*)"', match.group(1))


def cell(text: str) -> str:
    """`text` as Markdown in a table cell: punctuation that would format escaped."""
    return re.sub(r"([\\`*_\[\]<>|#])", r"\\\1", text)


def words(names: dict, key: str, what: str) -> str:
    if key not in names:
        raise DataError(f"{CATALOGUE}: no {key} ({what})")
    return names[key]


def unmarked(label: str) -> str:
    """`label` as the window draws it (`theme::mnemonic::Label::parse`): an `&` before a letter or
    a digit marks the access key and goes, `&&` is one `&`, an `&` before anything else stays."""
    text, at = "", 0
    while at < len(label):
        char, after = label[at], label[at + 1 : at + 2]
        if char == "&" and (after == "&" or after.isalnum()):
            text, at = text + after, at + 2
        else:
            text, at = text + char, at + 1
    return text


def shown(names: dict, key: str, what: str) -> str:
    """A label or a title from the catalogue without its access-key mark; help texts carry none."""
    return unmarked(words(names, key, what))


def value_cells(row: dict, names: dict) -> tuple[str, str]:
    """The values a row takes and its default, as table cells."""
    kind, variant = row["kind"], row["variant"]
    if variant == "Choice":
        labels = {c["value"]: shown(names, c["label"], row["key"]) for c in kind["choices"]}
        choices = ", ".join(f"{cell(label)} (`{value}`)" for value, label in labels.items())
        return f"One of {choices}", cell(labels[kind["default"]])
    text = KINDS[variant].format(min=kind.get("min"), max=kind.get("max"), choices="")
    default = kind["default"]
    if variant == "Bool":
        return text, "On" if default else "Off"
    if variant == "Int":
        return text, str(default)
    return text, f"`{default}`" if default else "*empty*"


def render(root: Path) -> str:
    try:
        names = json.loads(read(root, CATALOGUE))
    except ValueError as error:
        raise DataError(f"{CATALOGUE}: {error}") from error
    schema_text = read(root, SCHEMA)
    known = variants(schema_text, "SettingKind", SCHEMA)
    unknown = sorted(set(known) - set(KINDS))
    if unknown:
        raise DataError(f"{SCHEMA}: SettingKind::{', '.join(unknown)} has no words in settings_reference.py")
    rows = settings(root)
    pages = dialog(root, variants(schema_text, "SettingPage", SCHEMA))
    tabs, tab_titles = appearance_tabs(root)
    prefixes = protected_prefixes(root)
    for row in rows:
        row["protected"] = row["protected"] or row["key"].startswith(tuple(prefixes))

    page = HEADER
    for schema_page, title_key, dialog_page in pages:
        title = shown(names, title_key, f"page {dialog_page}")
        on_page = [row for row in rows if row["page"] == schema_page]
        page += f"\n## {title}\n"
        if dialog_page == "Appearance":
            placed = {key for _, keys in tabs for key in keys}
            stray = sorted(set(placed) - {row["key"] for row in on_page})
            if stray:
                raise DataError(f"{TABS}: APPEARANCE names keys of no Appearance row: {', '.join(stray)}")
            for at, (tab, keys) in enumerate(tabs):
                # A row no tab names stands on the first, as `tabs::appearance_tab` places it.
                tab_rows = [r for r in on_page if r["key"] in keys or (at == 0 and r["key"] not in placed)]
                tab_title = shown(names, tab_titles.get(tab, f"settings.tab.{tab}"), f"tab {tab}")
                page += f"\n### {title} > {tab_title}\n\n" + table(tab_rows, names, title)
        else:
            page += "\n" + table(on_page, names, title)
        if schema_page == "Plugins":
            installed = shown(names, tab_titles.get("Installed", ""), "tab Installed")
            page += PLUGINS_NOTE.format(installed=installed)
    protected = sum(row["protected"] for row in rows)
    restart = sum(row["restart"] for row in rows)
    page += (
        f"\n{len(rows)} settings on {len(pages)} pages: {protected} protected, {restart} taking "
        f"effect at the next start.\n"
    )
    return page


def table(rows: list[dict], names: dict, title: str) -> str:
    text = "| Setting | Key | Values | Default | Description |\n| --- | --- | --- | --- | --- |\n"
    for row in rows:
        values, default = value_cells(row, names)
        notes = [cell(words(names, row["help"], row["key"]))]
        if row["variant"] == "Keymap":
            notes.append(KEYMAP_NOTE)
        if row["protected"]:
            notes.append("**Protected.**")
        if row["restart"]:
            notes.append("**Restart.**")
        label = cell(shown(names, row["label"], row["key"]))
        text += f"| {label} | `{row['key']}` | {values} | {default} | {' '.join(notes)} |\n"
    if not rows:
        raise DataError(f"the page {title} shows no setting")
    return text


def main(argv: list[str]) -> int:
    if len(argv) < 3 or any(arg != "--check" for arg in argv[3:]):
        print("usage: settings_reference.py <repo root> <wiki dir> [--check]", file=sys.stderr)
        return 2
    root, wiki = Path(argv[1]), Path(argv[2])
    check = "--check" in argv[3:]
    try:
        page = render(root)
    except (DataError, RustError, OSError, ValueError, KeyError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 2
    target = wiki / PAGE
    if not wiki.is_dir():
        if check:
            print(f"==> no wiki at {wiki}: the settings data reads, the page is not checked")
            return 0
        print(f"error: no wiki at {wiki} (set RC_WIKI)", file=sys.stderr)
        return 2
    current = target.read_text(encoding="utf-8") if target.exists() else None
    if check:
        if current != page:
            print(f"{target} is stale: run scripts/settings-reference.sh", file=sys.stderr)
            return 1
        print(f"==> {target} is current")
        return 0
    if current == page:
        print(f"==> {target} was already current")
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(page, encoding="utf-8")
        print(f"==> wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
